def format_display_classification(predicted_class: str) -> str:
    """Returns the display label for a raw class name."""
    if not predicted_class:
        return "Unknown"
    normalized = predicted_class.strip().lower()
    if normalized in ["notumor", "no_tumor", "normal"]:
        return "No Tumor Detected by AI Model."
    if normalized == "glioma":
        return "Glioma"
    if normalized == "meningioma":
        return "Meningioma"
    if normalized == "pituitary":
        return "Pituitary Tumour"
    return predicted_class.replace("_", " ").title()


def generate_classification_summary(predicted_class: str, confidence: float, probabilities: dict = None) -> str:
    """
    Generates an objective summary that describes only the model output.
    No anatomical observations, radiological findings, or clinical conclusions
    are invented.
    """
    probabilities = probabilities or {}
    normalized = (predicted_class or "").strip().lower()
    display = format_display_classification(predicted_class)
    confidence_text = f"{float(confidence):.2f}%"

    ranked = sorted(
        ((key, float(value)) for key, value in probabilities.items()),
        key=lambda item: item[1],
        reverse=True,
    )
    ranking_text = ""
    if ranked:
        ranking_parts = [
            f"{format_display_classification(key)} {value:.2f}%"
            for key, value in ranked
        ]
        ranking_text = " The complete softmax distribution was: " + "; ".join(ranking_parts) + "."

    if normalized in ["notumor", "no_tumor", "normal"]:
        return (
            f"The VGG16 classifier assigned its highest softmax probability to the "
            f"No Tumor class ({confidence_text}), which is displayed as \"No Tumor Detected "
            f"by AI Model.\" This result reflects the model's statistical ranking of the four "
            f"trained categories only; it does not confirm the absence of disease or of any "
            f"other neurological condition.{ranking_text}"
        )

    if normalized in ["glioma", "meningioma", "pituitary"]:
        return (
            f"The VGG16 classifier assigned its highest softmax probability to the "
            f"{display} class ({confidence_text}) for the uploaded image. This statement "
            f"describes the model's statistical output only; no radiological feature, lesion "
            f"boundary, or anatomical observation has been measured by this report.{ranking_text}"
        )

    return (
        f"The VGG16 classifier returned the category \"{display}\" with a highest-class "
        f"probability of {confidence_text}. This statement describes model output only.{ranking_text}"
    )


